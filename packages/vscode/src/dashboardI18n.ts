export const DASHBOARD_CATALOGS: Record<SupportedLocale, DashboardCatalog> = {
  en,
  "zh-cn": zhCn,
};

export function resolveDashboardLocale(
  preference: LanguagePreference,
  vscodeLanguage?: string,
): SupportedLocale {
  if (preference !== "auto") return preference;
  return typeof vscodeLanguage === "string" && /^zh(?:-|$)/i.test(vscodeLanguage)
    ? "zh-cn"
    : "en";
}

export function translate(
  locale: SupportedLocale,
  key: DashboardTranslationKey,
  args: TranslationArgs = {},
): string {
  const template = DASHBOARD_CATALOGS[locale]?.[key] ?? DASHBOARD_CATALOGS.en[key];
  return template.replace(/\{([^{}]+)\}/g, (placeholder, name: string) => (
    Object.prototype.hasOwnProperty.call(args, name) ? String(args[name]) : placeholder
  ));
}

export function dashboardLocaleTag(locale: SupportedLocale): "en-US" | "zh-CN" {
  return locale === "zh-cn" ? "zh-CN" : "en-US";
}
